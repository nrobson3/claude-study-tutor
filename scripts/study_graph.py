#!/usr/bin/env python3
"""Study Graph: the custom knowledge-graph view of the concept notes.

The engine lives in tools/study-graph/ (core.js, plugin.js, styles.css). This script
packages it two ways and exports the data.

Commands
    build          Write the Obsidian plugin into .obsidian/plugins/study-graph/
                   (main.js = core.js + plugin.js, plus styles.css and manifest.json).
    check-build    Exit 1 if the built plugin is out of date with tools/study-graph/.
    export [-o F]  Print (or write) the graph data as JSON: {nodes, edges, vault}.
    html [--open]  Write a standalone page to .cache/study-graph.html (same view, opens in
                   a browser; "Open note" buttons use obsidian:// links).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import webbrowser
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import graph  # noqa: E402  (same folder)

VAULT = HERE.parent
SRC = VAULT / "tools" / "study-graph"
PLUGIN_DIR = VAULT / ".obsidian" / "plugins" / "study-graph"
HTML_OUT = VAULT / ".cache" / "study-graph.html"
HEADER = "/* GENERATED by scripts/study_graph.py build from tools/study-graph/. Edit the sources, then rebuild. */\n"


def export_data() -> dict:
    concepts = graph.load_concepts()
    idx = graph.concept_index(concepts)
    nodes, edges, seen = [], [], set()
    for c in concepts:
        rel = c.path.relative_to(VAULT).as_posix()
        nodes.append({
            "id": rel,
            "name": c.name,
            "course": c.course,
            "status": c.status if c.status in graph.STATUSES else "unknown",
            "kind": c.kind,
            "statement": c.statement,
            "aliases": c.aliases,
            "slide": c.slide,
        })
        for t in c.follows_from:
            other = idx.get(t.strip().lower())
            if other is not None and other is not c:
                target = other.path.relative_to(VAULT).as_posix()
                if (rel, target) not in seen:
                    seen.add((rel, target))
                    edges.append({"source": rel, "target": target})
    return {"nodes": nodes, "edges": edges, "vault": VAULT.name}


def built_files() -> dict[Path, str]:
    core = (SRC / "core.js").read_text(encoding="utf-8")
    plugin = (SRC / "plugin.js").read_text(encoding="utf-8")
    return {
        PLUGIN_DIR / "main.js": HEADER + core.rstrip() + "\n\n" + plugin.rstrip() + "\n",
        PLUGIN_DIR / "styles.css": (SRC / "styles.css").read_text(encoding="utf-8"),
        PLUGIN_DIR / "manifest.json": (SRC / "manifest.json").read_text(encoding="utf-8"),
    }


def cmd_build(_args) -> None:
    PLUGIN_DIR.mkdir(parents=True, exist_ok=True)
    for path, text in built_files().items():
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"wrote {path.relative_to(VAULT).as_posix()}")


def cmd_check_build(_args) -> None:
    stale = []
    for path, text in built_files().items():
        try:
            current = path.read_text(encoding="utf-8")
        except OSError:
            current = None
        if current is None or current.replace("\r\n", "\n") != text.replace("\r\n", "\n"):
            stale.append(path.relative_to(VAULT).as_posix())
    if stale:
        print("Out of date (run: python scripts/study_graph.py build):")
        for s in stale:
            print("  " + s)
        sys.exit(1)
    print("Plugin build is up to date.")


def cmd_export(args) -> None:
    text = json.dumps(export_data(), ensure_ascii=False, indent=1)
    if args.out:
        Path(args.out).write_text(text, encoding="utf-8")
        print(f"wrote {args.out}")
    else:
        print(text)


def render_html(data: dict) -> str:
    template = (SRC / "standalone.html").read_text(encoding="utf-8")
    # Inside <script>, "<" must never appear raw ("</script>" ends it, "<!--" confuses the parser):
    # "\u003c" means the same character to JSON and JS. U+2028/9 are line breaks to older JS.
    payload = (json.dumps(data, ensure_ascii=False)
               .replace("<", "\\u003c").replace("\u2028", "\\u2028").replace("\u2029", "\\u2029"))
    parts = {
        "DATA": payload,
        "CORE": re.sub(r"</(script)", r"<\\/\1", (SRC / "core.js").read_text(encoding="utf-8"), flags=re.I),
        "STYLES": (SRC / "styles.css").read_text(encoding="utf-8"),
    }
    # One pass, so text that was just inserted (a statement, say) is never scanned for markers.
    return re.sub(r"/\*(DATA|CORE|STYLES)\*/", lambda m: parts[m.group(1)], template)


def cmd_html(args) -> None:
    HTML_OUT.parent.mkdir(parents=True, exist_ok=True)
    HTML_OUT.write_text(render_html(export_data()), encoding="utf-8")
    print(f"wrote {HTML_OUT}")
    if args.open:
        webbrowser.open(HTML_OUT.as_uri())


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Study Graph build, export and preview")
    sub = parser.add_subparsers(dest="cmd", required=True)
    sub.add_parser("build").set_defaults(func=cmd_build)
    sub.add_parser("check-build").set_defaults(func=cmd_check_build)
    p = sub.add_parser("export")
    p.add_argument("-o", "--out")
    p.set_defaults(func=cmd_export)
    p = sub.add_parser("html")
    p.add_argument("--open", action="store_true")
    p.set_defaults(func=cmd_html)
    args = parser.parse_args(argv)
    args.func(args)


if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    main()
